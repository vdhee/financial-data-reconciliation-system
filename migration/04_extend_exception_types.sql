-- Existing CHK_EXCEPTION_TYPE allows only the original four types.
-- Run after RECON_EXCEPTIONS exists and before compiling the v2 procedure.
ALTER TABLE RECON_EXCEPTIONS DROP CONSTRAINT CHK_EXCEPTION_TYPE;

ALTER TABLE RECON_EXCEPTIONS ADD CONSTRAINT CHK_EXCEPTION_TYPE
CHECK (EXCEPTION_TYPE IN (
    'MISMATCH',
    'CURRENCY_MISMATCH',
    'MISSING_IN_SOURCE',
    'MISSING_IN_TARGET',
    'MISSING_DATA'
));

ALTER TABLE RECON_RECORDS DROP CONSTRAINT CHK_RECON_STATUS;

ALTER TABLE RECON_RECORDS ADD CONSTRAINT CHK_RECON_STATUS
CHECK (RECON_STATUS IN (
    'PENDING',
    'MATCHED',
    'MISMATCH',
    'CURRENCY_MISMATCH',
    'MISSING_DATA',
    'MISSING_IN_SOURCE',
    'MISSING_IN_TARGET'
));
