CREATE TABLE RECON_RUN_HISTORY (
    RUN_ID NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_RECON_RUN_HISTORY PRIMARY KEY,
    BATCH_ID NUMBER NOT NULL,
    RUN_NUMBER NUMBER NOT NULL,
    RUN_STATUS VARCHAR2(20) NOT NULL,
    STARTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ENDED_AT TIMESTAMP,
    SOURCE_ROW_COUNT NUMBER,
    TARGET_ROW_COUNT NUMBER,
    RECON_ROW_COUNT NUMBER,
    ERROR_CODE NUMBER,
    ERROR_MESSAGE VARCHAR2(2000),
    CONSTRAINT FK_RUN_BATCH FOREIGN KEY (BATCH_ID) REFERENCES RECON_BATCHES(BATCH_ID),
    CONSTRAINT UK_RUN_BATCH_NUMBER UNIQUE (BATCH_ID, RUN_NUMBER),
    CONSTRAINT CK_RUN_STATUS CHECK (RUN_STATUS IN ('STARTED','COMPLETED','FAILED')),
    CONSTRAINT CK_RUN_COUNTS CHECK (
      (SOURCE_ROW_COUNT IS NULL OR SOURCE_ROW_COUNT >= 0) AND
      (TARGET_ROW_COUNT IS NULL OR TARGET_ROW_COUNT >= 0) AND
      (RECON_ROW_COUNT IS NULL OR RECON_ROW_COUNT >= 0)
    )
);

CREATE TABLE BATCH_CONTROL_TOTALS (
    CONTROL_TOTAL_ID NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_BATCH_CONTROL_TOTALS PRIMARY KEY,
    BATCH_ID NUMBER NOT NULL,
    SYSTEM_SIDE VARCHAR2(10) NOT NULL,
    TRANSACTION_COUNT NUMBER NOT NULL,
    TOTAL_AMOUNT NUMBER(20,2),
    CURRENCY_CODE CHAR(3),
    CAPTURED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_CONTROL_BATCH FOREIGN KEY (BATCH_ID) REFERENCES RECON_BATCHES(BATCH_ID),
    CONSTRAINT CK_CONTROL_SIDE CHECK (SYSTEM_SIDE IN ('SOURCE','TARGET')),
    CONSTRAINT CK_CONTROL_COUNT CHECK (TRANSACTION_COUNT >= 0),
    CONSTRAINT FK_CONTROL_CURRENCY FOREIGN KEY (CURRENCY_CODE) REFERENCES CURRENCY_REFERENCE(CURRENCY_CODE),
    CONSTRAINT UK_CONTROL_BATCH_SIDE UNIQUE (BATCH_ID, SYSTEM_SIDE)
);

CREATE TABLE DATA_QUALITY_ISSUES (
    ISSUE_ID NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_DATA_QUALITY_ISSUES PRIMARY KEY,
    BATCH_ID NUMBER NOT NULL,
    SYSTEM_SIDE VARCHAR2(10) NOT NULL,
    TRANSACTION_REF VARCHAR2(100),
    ISSUE_TYPE VARCHAR2(30) NOT NULL,
    ISSUE_DETAILS VARCHAR2(1000),
    ISSUE_STATUS VARCHAR2(15) DEFAULT 'OPEN' NOT NULL,
    DETECTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_DQ_BATCH FOREIGN KEY (BATCH_ID) REFERENCES RECON_BATCHES(BATCH_ID),
    CONSTRAINT CK_DQ_SIDE CHECK (SYSTEM_SIDE IN ('SOURCE','TARGET')),
    CONSTRAINT CK_DQ_TYPE CHECK (ISSUE_TYPE IN ('NULL_REFERENCE','NULL_AMOUNT','INVALID_CURRENCY','DUPLICATE_REFERENCE','INVALID_AMOUNT')),
    CONSTRAINT CK_DQ_STATUS CHECK (ISSUE_STATUS IN ('OPEN','RESOLVED','IGNORED'))
);

CREATE TABLE TRANSACTION_DUPLICATES (
    DUPLICATE_ID NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_TRANSACTION_DUPLICATES PRIMARY KEY,
    BATCH_ID NUMBER NOT NULL,
    SYSTEM_SIDE VARCHAR2(10) NOT NULL,
    TRANSACTION_REF VARCHAR2(100) NOT NULL,
    DUPLICATE_COUNT NUMBER NOT NULL,
    DETECTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_DUP_BATCH FOREIGN KEY (BATCH_ID) REFERENCES RECON_BATCHES(BATCH_ID),
    CONSTRAINT CK_DUP_SIDE CHECK (SYSTEM_SIDE IN ('SOURCE','TARGET')),
    CONSTRAINT CK_DUP_COUNT CHECK (DUPLICATE_COUNT > 1),
    CONSTRAINT UK_DUP_GROUP UNIQUE (BATCH_ID, SYSTEM_SIDE, TRANSACTION_REF)
);

CREATE TABLE EXCEPTION_ASSIGNMENTS (
    ASSIGNMENT_ID NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_EXCEPTION_ASSIGNMENTS PRIMARY KEY,
    EXCEPTION_ID NUMBER NOT NULL,
    ASSIGNED_TO VARCHAR2(100) NOT NULL,
    ASSIGNED_BY VARCHAR2(100) NOT NULL,
    ASSIGNED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UNASSIGNED_AT TIMESTAMP,
    NOTES VARCHAR2(1000),
    CONSTRAINT FK_ASSIGN_EXCEPTION FOREIGN KEY (EXCEPTION_ID) REFERENCES RECON_EXCEPTIONS(EXCEPTION_ID),
    CONSTRAINT CK_ASSIGN_DATES CHECK (UNASSIGNED_AT IS NULL OR UNASSIGNED_AT >= ASSIGNED_AT)
);

CREATE TABLE EXCEPTION_HISTORY (
    HISTORY_ID NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_EXCEPTION_HISTORY PRIMARY KEY,
    EXCEPTION_ID NUMBER NOT NULL,
    OLD_STATUS VARCHAR2(20),
    NEW_STATUS VARCHAR2(20) NOT NULL,
    CHANGED_BY VARCHAR2(100) NOT NULL,
    CHANGE_REASON VARCHAR2(1000),
    CHANGED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_EXH_EXCEPTION FOREIGN KEY (EXCEPTION_ID) REFERENCES RECON_EXCEPTIONS(EXCEPTION_ID),
    CONSTRAINT CK_EXH_NEW_STATUS CHECK (NEW_STATUS IN ('OPEN','INVESTIGATING','RESOLVED'))
);

CREATE TABLE RECON_AUDIT_LOG (
    AUDIT_ID NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_RECON_AUDIT_LOG PRIMARY KEY,
    BATCH_ID NUMBER,
    RUN_ID NUMBER,
    EVENT_TYPE VARCHAR2(40) NOT NULL,
    EVENT_STATUS VARCHAR2(20) NOT NULL,
    EVENT_MESSAGE VARCHAR2(2000),
    EVENT_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DB_USER_NAME VARCHAR2(128) DEFAULT USER NOT NULL,
    CONSTRAINT FK_AUDIT_BATCH FOREIGN KEY (BATCH_ID) REFERENCES RECON_BATCHES(BATCH_ID),
    CONSTRAINT CK_AUDIT_STATUS CHECK (EVENT_STATUS IN ('INFO','SUCCESS','WARNING','ERROR'))
);
