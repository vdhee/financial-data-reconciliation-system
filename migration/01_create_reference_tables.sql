-- Additive migration for the existing project schema.
CREATE TABLE SOURCE_SYSTEMS (
    SYSTEM_CODE VARCHAR2(50) CONSTRAINT PK_SOURCE_SYSTEMS PRIMARY KEY,
    SYSTEM_NAME VARCHAR2(120) NOT NULL,
    SYSTEM_ROLE VARCHAR2(10) NOT NULL,
    ACTIVE_FLAG CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_SOURCE_SYSTEM_ROLE CHECK (SYSTEM_ROLE IN ('SOURCE','TARGET','BOTH')),
    CONSTRAINT CK_SOURCE_SYSTEM_ACTIVE CHECK (ACTIVE_FLAG IN ('Y','N'))
);

CREATE TABLE CURRENCY_REFERENCE (
    CURRENCY_CODE CHAR(3) CONSTRAINT PK_CURRENCY_REFERENCE PRIMARY KEY,
    CURRENCY_NAME VARCHAR2(60) NOT NULL,
    DECIMAL_PLACES NUMBER(1) DEFAULT 2 NOT NULL,
    ACTIVE_FLAG CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT CK_CURRENCY_DECIMALS CHECK (DECIMAL_PLACES BETWEEN 0 AND 4),
    CONSTRAINT CK_CURRENCY_ACTIVE CHECK (ACTIVE_FLAG IN ('Y','N'))
);

CREATE TABLE RECON_RULES (
    RULE_ID NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_RECON_RULES PRIMARY KEY,
    RULE_CODE VARCHAR2(40) NOT NULL,
    RULE_NAME VARCHAR2(120) NOT NULL,
    RULE_TYPE VARCHAR2(30) NOT NULL,
    AMOUNT_TOLERANCE NUMBER(15,2) DEFAULT 0 NOT NULL,
    SEVERITY VARCHAR2(10) DEFAULT 'MEDIUM' NOT NULL,
    ACTIVE_FLAG CHAR(1) DEFAULT 'Y' NOT NULL,
    EFFECTIVE_FROM DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    EFFECTIVE_TO DATE,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_RECON_RULE_CODE UNIQUE (RULE_CODE),
    CONSTRAINT CK_RECON_RULE_TYPE CHECK (RULE_TYPE IN ('AMOUNT','CURRENCY','MISSING','DUPLICATE','DATA_QUALITY')),
    CONSTRAINT CK_RECON_RULE_SEVERITY CHECK (SEVERITY IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    CONSTRAINT CK_RECON_RULE_ACTIVE CHECK (ACTIVE_FLAG IN ('Y','N')),
    CONSTRAINT CK_RECON_RULE_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM),
    CONSTRAINT CK_RECON_RULE_TOLERANCE CHECK (AMOUNT_TOLERANCE >= 0)
);
