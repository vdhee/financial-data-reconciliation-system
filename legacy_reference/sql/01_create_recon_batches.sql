CREATE TABLE RECON_BATCHES (
    BATCH_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BATCH_NAME     VARCHAR2(100) NOT NULL,
    SOURCE_SYSTEM  VARCHAR2(50) NOT NULL,
    TARGET_SYSTEM  VARCHAR2(50) NOT NULL,
    BATCH_DATE     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    BATCH_STATUS   VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT CHK_BATCH_STATUS
        CHECK (BATCH_STATUS IN (
            'PENDING', 'PROCESSING', 'COMPLETED', 'FAILED'
        ))
);