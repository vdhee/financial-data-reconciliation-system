SELECT b.BATCH_ID, b.BATCH_NAME, b.BATCH_STATUS,
       COUNT(r.RECORD_ID) AS TOTAL_TRANSACTIONS,
       SUM(CASE WHEN r.RECON_STATUS = 'MATCHED' THEN 1 ELSE 0 END) AS MATCHED_COUNT,
       SUM(CASE WHEN r.RECON_STATUS = 'MISMATCH' THEN 1 ELSE 0 END) AS MISMATCH_COUNT,
       SUM(CASE WHEN r.RECON_STATUS = 'MISSING_IN_SOURCE' THEN 1 ELSE 0 END) AS MISSING_IN_SOURCE_COUNT,
       SUM(CASE WHEN r.RECON_STATUS = 'MISSING_IN_TARGET' THEN 1 ELSE 0 END) AS MISSING_IN_TARGET_COUNT,
       SUM(CASE WHEN r.RECON_STATUS = 'MISSING_DATA' THEN 1 ELSE 0 END) AS MISSING_DATA_COUNT,
       ROUND(100 * SUM(CASE WHEN r.RECON_STATUS = 'MATCHED' THEN 1 ELSE 0 END)
             / NULLIF(COUNT(r.RECORD_ID), 0), 2) AS MATCH_RATE_PERCENT,
       SUM(CASE WHEN r.RECON_STATUS = 'MISMATCH'
                THEN ABS(r.SOURCE_AMOUNT - r.TARGET_AMOUNT) ELSE 0 END) AS TOTAL_MISMATCH_AMOUNT
FROM RECON_BATCHES b
LEFT JOIN RECON_RECORDS r ON r.BATCH_ID = b.BATCH_ID
GROUP BY b.BATCH_ID, b.BATCH_NAME, b.BATCH_STATUS
ORDER BY b.BATCH_ID;
