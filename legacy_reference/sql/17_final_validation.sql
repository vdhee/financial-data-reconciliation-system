
-- 1. Check batch status
SELECT
    BATCH_ID,
    BATCH_NAME,
    BATCH_STATUS
FROM RECON_BATCHES
ORDER BY BATCH_ID;

-- 2. Verify reconciliation results
SELECT
    RECON_STATUS,
    COUNT(*) AS RECORD_COUNT,
    SUM(
        CASE
            WHEN RECON_STATUS = 'MISMATCH'
            THEN ABS(SOURCE_AMOUNT - TARGET_AMOUNT)
            ELSE 0
        END
    ) AS MISMATCH_AMOUNT
FROM RECON_RECORDS
GROUP BY RECON_STATUS
ORDER BY RECON_STATUS;

-- 3. Check exception status
SELECT
    EXCEPTION_STATUS,
    COUNT(*) AS EXCEPTION_COUNT
FROM RECON_EXCEPTIONS
GROUP BY EXCEPTION_STATUS
ORDER BY EXCEPTION_STATUS;

-- 4. Check for duplicate transaction references within a batch
SELECT
    BATCH_ID,
    TRANSACTION_REF,
    COUNT(*) AS DUPLICATE_COUNT
FROM RECON_RECORDS
GROUP BY BATCH_ID, TRANSACTION_REF
HAVING COUNT(*) > 1;
