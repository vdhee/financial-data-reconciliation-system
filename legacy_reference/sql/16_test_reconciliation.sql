-- Read-only smoke checks; run after compiling the procedure and package.
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM USER_OBJECTS
WHERE OBJECT_NAME IN ('PRC_RECONCILE_BATCH','PKG_RECONCILIATION')
ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT BATCH_ID, BATCH_NAME, BATCH_STATUS
FROM RECON_BATCHES
ORDER BY BATCH_ID;

SELECT BATCH_ID, RECON_STATUS, COUNT(*) AS RECORD_COUNT
FROM RECON_RECORDS
GROUP BY BATCH_ID, RECON_STATUS
ORDER BY BATCH_ID, RECON_STATUS;

SELECT r.BATCH_ID, e.EXCEPTION_TYPE, e.EXCEPTION_STATUS,
       COUNT(*) AS EXCEPTION_COUNT, SUM(e.EXCEPTION_AMOUNT) AS TOTAL_EXCEPTION_AMOUNT
FROM RECON_EXCEPTIONS e
JOIN RECON_RECORDS r ON r.RECORD_ID = e.RECORD_ID
GROUP BY r.BATCH_ID, e.EXCEPTION_TYPE, e.EXCEPTION_STATUS
ORDER BY r.BATCH_ID, e.EXCEPTION_TYPE, e.EXCEPTION_STATUS;

SELECT PKG_RECONCILIATION.FN_AMOUNT_DIFFERENCE(3000, 2800) AS EXPECTED_200
FROM DUAL;
