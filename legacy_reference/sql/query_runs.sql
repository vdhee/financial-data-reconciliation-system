SELECT
    s.TRANSACTION_REF,
    s.AMOUNT AS SOURCE_AMOUNT,
    t.AMOUNT AS TARGET_AMOUNT,
    CASE
        WHEN t.TRANSACTION_REF IS NULL
            THEN 'MISSING_IN_TARGET'
        WHEN s.AMOUNT IS NULL OR t.AMOUNT IS NULL
            THEN 'MISSING_DATA'
        WHEN s.AMOUNT = t.AMOUNT
            THEN 'MATCHED'
        ELSE 'MISMATCH'
    END AS RECON_STATUS,
    CASE
        WHEN t.TRANSACTION_REF IS NULL
          OR s.AMOUNT IS NULL
          OR t.AMOUNT IS NULL
            THEN NULL
        ELSE ABS(s.AMOUNT - t.AMOUNT)
    END AS DIFFERENCE_AMOUNT
FROM SOURCE_TRANSACTIONS s
LEFT JOIN TARGET_TRANSACTIONS t
    ON s.BATCH_ID = t.BATCH_ID
   AND s.TRANSACTION_REF = t.TRANSACTION_REF
WHERE s.BATCH_ID = 1
ORDER BY s.TRANSACTION_REF;

