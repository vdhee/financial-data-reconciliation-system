CREATE OR REPLACE PACKAGE PKG_RECONCILIATION AS
    FUNCTION FN_AMOUNT_DIFFERENCE(P_SOURCE_AMOUNT IN NUMBER, P_TARGET_AMOUNT IN NUMBER)
        RETURN NUMBER;
    PROCEDURE PRC_LOAD_EXCEPTIONS(P_BATCH_ID IN NUMBER);
END PKG_RECONCILIATION;
/

CREATE OR REPLACE PACKAGE BODY PKG_RECONCILIATION AS
    FUNCTION FN_AMOUNT_DIFFERENCE(P_SOURCE_AMOUNT IN NUMBER, P_TARGET_AMOUNT IN NUMBER)
        RETURN NUMBER
    IS
    BEGIN
        IF P_SOURCE_AMOUNT IS NULL OR P_TARGET_AMOUNT IS NULL THEN
            RETURN NULL;
        END IF;
        RETURN ABS(P_SOURCE_AMOUNT - P_TARGET_AMOUNT);
    END FN_AMOUNT_DIFFERENCE;

    PROCEDURE PRC_LOAD_EXCEPTIONS(P_BATCH_ID IN NUMBER)
    IS
    BEGIN
        INSERT INTO RECON_EXCEPTIONS (RECORD_ID, EXCEPTION_TYPE, EXCEPTION_AMOUNT)
        SELECT r.RECORD_ID, r.RECON_STATUS,
               CASE WHEN r.RECON_STATUS = 'MISMATCH'
                    THEN FN_AMOUNT_DIFFERENCE(r.SOURCE_AMOUNT, r.TARGET_AMOUNT)
                    ELSE NULL END
        FROM RECON_RECORDS r
        WHERE r.BATCH_ID = P_BATCH_ID
          AND r.RECON_STATUS IN ('MISMATCH','MISSING_IN_SOURCE','MISSING_IN_TARGET','MISSING_DATA')
          AND NOT EXISTS (
              SELECT 1 FROM RECON_EXCEPTIONS e WHERE e.RECORD_ID = r.RECORD_ID
          );
    END PRC_LOAD_EXCEPTIONS;
END PKG_RECONCILIATION;
/
