CREATE OR REPLACE PACKAGE PKG_RECON_SUPPORT AS
    FUNCTION FN_AMOUNT_DIFFERENCE(P_SOURCE_AMOUNT NUMBER, P_TARGET_AMOUNT NUMBER)
        RETURN NUMBER;

    PROCEDURE PRC_LOG_EVENT(
        P_BATCH_ID IN NUMBER,
        P_RUN_ID IN NUMBER,
        P_EVENT_TYPE IN VARCHAR2,
        P_EVENT_STATUS IN VARCHAR2,
        P_EVENT_MESSAGE IN VARCHAR2
    );

    PROCEDURE PRC_LOAD_EXCEPTIONS(P_BATCH_ID IN NUMBER);
END PKG_RECON_SUPPORT;
/

CREATE OR REPLACE PACKAGE BODY PKG_RECON_SUPPORT AS
    FUNCTION FN_AMOUNT_DIFFERENCE(P_SOURCE_AMOUNT NUMBER, P_TARGET_AMOUNT NUMBER)
        RETURN NUMBER
    IS
    BEGIN
        IF P_SOURCE_AMOUNT IS NULL OR P_TARGET_AMOUNT IS NULL THEN
            RETURN NULL;
        END IF;
        RETURN ABS(P_SOURCE_AMOUNT - P_TARGET_AMOUNT);
    END FN_AMOUNT_DIFFERENCE;

    PROCEDURE PRC_LOG_EVENT(
        P_BATCH_ID IN NUMBER,
        P_RUN_ID IN NUMBER,
        P_EVENT_TYPE IN VARCHAR2,
        P_EVENT_STATUS IN VARCHAR2,
        P_EVENT_MESSAGE IN VARCHAR2
    )
    IS
        PRAGMA AUTONOMOUS_TRANSACTION;
    BEGIN
        INSERT INTO RECON_AUDIT_LOG (
            BATCH_ID, RUN_ID, EVENT_TYPE, EVENT_STATUS, EVENT_MESSAGE
        ) VALUES (
            P_BATCH_ID, P_RUN_ID, P_EVENT_TYPE, P_EVENT_STATUS, SUBSTR(P_EVENT_MESSAGE,1,2000)
        );
        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            -- Logging failure must not mask the original business operation.
            NULL;
    END PRC_LOG_EVENT;

    PROCEDURE PRC_LOAD_EXCEPTIONS(P_BATCH_ID IN NUMBER)
    IS
    BEGIN
        INSERT INTO RECON_EXCEPTIONS (RECORD_ID, EXCEPTION_TYPE, EXCEPTION_AMOUNT)
        SELECT r.RECORD_ID, r.RECON_STATUS,
               CASE WHEN r.RECON_STATUS = 'MISMATCH'
                    THEN FN_AMOUNT_DIFFERENCE(r.SOURCE_AMOUNT, r.TARGET_AMOUNT)
                    ELSE NULL END
        FROM RECON_RECORDS r
        WHERE r.BATCH_ID = P_BATCH_ID
          AND r.RECON_STATUS IN ('MISMATCH','CURRENCY_MISMATCH','MISSING_IN_SOURCE','MISSING_IN_TARGET','MISSING_DATA')
          AND NOT EXISTS (
              SELECT 1 FROM RECON_EXCEPTIONS e WHERE e.RECORD_ID = r.RECORD_ID
          );
    END PRC_LOAD_EXCEPTIONS;
END PKG_RECON_SUPPORT;
/
