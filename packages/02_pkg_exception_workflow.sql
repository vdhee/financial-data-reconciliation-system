CREATE OR REPLACE PACKAGE PKG_EXCEPTION_WORKFLOW AS
    PROCEDURE PRC_CHANGE_STATUS(
        P_EXCEPTION_ID IN NUMBER,
        P_NEW_STATUS IN VARCHAR2,
        P_CHANGED_BY IN VARCHAR2,
        P_REASON IN VARCHAR2
    );

    PROCEDURE PRC_ASSIGN_EXCEPTION(
        P_EXCEPTION_ID IN NUMBER,
        P_ASSIGNED_TO IN VARCHAR2,
        P_ASSIGNED_BY IN VARCHAR2,
        P_NOTES IN VARCHAR2 DEFAULT NULL
    );
END PKG_EXCEPTION_WORKFLOW;
/

CREATE OR REPLACE PACKAGE BODY PKG_EXCEPTION_WORKFLOW AS
    PROCEDURE PRC_CHANGE_STATUS(
        P_EXCEPTION_ID IN NUMBER,
        P_NEW_STATUS IN VARCHAR2,
        P_CHANGED_BY IN VARCHAR2,
        P_REASON IN VARCHAR2
    )
    IS
        V_OLD_STATUS RECON_EXCEPTIONS.EXCEPTION_STATUS%TYPE;
    BEGIN
        IF P_NEW_STATUS NOT IN ('OPEN','INVESTIGATING','RESOLVED') THEN
            RAISE_APPLICATION_ERROR(-20201,'Invalid exception status.');
        END IF;

        SELECT EXCEPTION_STATUS
          INTO V_OLD_STATUS
          FROM RECON_EXCEPTIONS
         WHERE EXCEPTION_ID=P_EXCEPTION_ID
         FOR UPDATE;

        IF V_OLD_STATUS = P_NEW_STATUS THEN
            RETURN;
        END IF;

        UPDATE RECON_EXCEPTIONS
           SET EXCEPTION_STATUS=P_NEW_STATUS,
               RESOLVED_AT=CASE WHEN P_NEW_STATUS='RESOLVED' THEN SYSTIMESTAMP ELSE NULL END
         WHERE EXCEPTION_ID=P_EXCEPTION_ID;

        INSERT INTO EXCEPTION_HISTORY(
            EXCEPTION_ID, OLD_STATUS, NEW_STATUS, CHANGED_BY, CHANGE_REASON
        ) VALUES (
            P_EXCEPTION_ID, V_OLD_STATUS, P_NEW_STATUS, P_CHANGED_BY, P_REASON
        );
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20202,'Exception ID does not exist.');
    END PRC_CHANGE_STATUS;

    PROCEDURE PRC_ASSIGN_EXCEPTION(
        P_EXCEPTION_ID IN NUMBER,
        P_ASSIGNED_TO IN VARCHAR2,
        P_ASSIGNED_BY IN VARCHAR2,
        P_NOTES IN VARCHAR2 DEFAULT NULL
    )
    IS
    BEGIN
        IF TRIM(P_ASSIGNED_TO) IS NULL OR TRIM(P_ASSIGNED_BY) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20203,'Assignee and assigning user are required.');
        END IF;

        UPDATE EXCEPTION_ASSIGNMENTS
           SET UNASSIGNED_AT=SYSTIMESTAMP
         WHERE EXCEPTION_ID=P_EXCEPTION_ID
           AND UNASSIGNED_AT IS NULL;

        INSERT INTO EXCEPTION_ASSIGNMENTS(
            EXCEPTION_ID, ASSIGNED_TO, ASSIGNED_BY, NOTES
        ) VALUES (
            P_EXCEPTION_ID, P_ASSIGNED_TO, P_ASSIGNED_BY, P_NOTES
        );
    END PRC_ASSIGN_EXCEPTION;
END PKG_EXCEPTION_WORKFLOW;
