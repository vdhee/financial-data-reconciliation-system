CREATE OR REPLACE PROCEDURE PRC_RECONCILE_BATCH_V2(P_BATCH_ID IN NUMBER)
AS
    V_BATCH_STATUS RECON_BATCHES.BATCH_STATUS%TYPE;
    V_RUN_NUMBER NUMBER;
    V_RUN_ID NUMBER;
    V_SOURCE_COUNT NUMBER;
    V_TARGET_COUNT NUMBER;
    V_RECON_COUNT NUMBER;
BEGIN
    SELECT BATCH_STATUS
      INTO V_BATCH_STATUS
      FROM RECON_BATCHES
     WHERE BATCH_ID = P_BATCH_ID;

    IF V_BATCH_STATUS <> 'PENDING' THEN
        RAISE_APPLICATION_ERROR(-20101, 'Only PENDING batches can be reconciled.');
    END IF;

    -- Atomic claim: a concurrent session can only claim a still-pending batch.
    UPDATE RECON_BATCHES
       SET BATCH_STATUS = 'PROCESSING'
     WHERE BATCH_ID = P_BATCH_ID
       AND BATCH_STATUS = 'PENDING';

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20102, 'Batch is no longer PENDING.');
    END IF;

    SELECT NVL(MAX(RUN_NUMBER),0) + 1
      INTO V_RUN_NUMBER
      FROM RECON_RUN_HISTORY
     WHERE BATCH_ID = P_BATCH_ID;

    INSERT INTO RECON_RUN_HISTORY(BATCH_ID, RUN_NUMBER, RUN_STATUS, STARTED_AT)
    VALUES (P_BATCH_ID, V_RUN_NUMBER, 'STARTED', SYSTIMESTAMP)
    RETURNING RUN_ID INTO V_RUN_ID;

    PKG_RECON_SUPPORT.PRC_LOG_EVENT(
        P_BATCH_ID, V_RUN_ID, 'RECON_START', 'INFO', 'Reconciliation started.'
    );

    -- Record duplicate transaction references before joining.
    INSERT INTO TRANSACTION_DUPLICATES(BATCH_ID, SYSTEM_SIDE, TRANSACTION_REF, DUPLICATE_COUNT)
    SELECT BATCH_ID, 'SOURCE', TRANSACTION_REF, COUNT(*)
      FROM SOURCE_TRANSACTIONS
     WHERE BATCH_ID = P_BATCH_ID
       AND TRANSACTION_REF IS NOT NULL
     GROUP BY BATCH_ID, TRANSACTION_REF
    HAVING COUNT(*) > 1
       AND NOT EXISTS (
           SELECT 1 FROM TRANSACTION_DUPLICATES d
            WHERE d.BATCH_ID = P_BATCH_ID
              AND d.SYSTEM_SIDE = 'SOURCE'
              AND d.TRANSACTION_REF = SOURCE_TRANSACTIONS.TRANSACTION_REF
       );

    INSERT INTO TRANSACTION_DUPLICATES(BATCH_ID, SYSTEM_SIDE, TRANSACTION_REF, DUPLICATE_COUNT)
    SELECT BATCH_ID, 'TARGET', TRANSACTION_REF, COUNT(*)
      FROM TARGET_TRANSACTIONS
     WHERE BATCH_ID = P_BATCH_ID
       AND TRANSACTION_REF IS NOT NULL
     GROUP BY BATCH_ID, TRANSACTION_REF
    HAVING COUNT(*) > 1
       AND NOT EXISTS (
           SELECT 1 FROM TRANSACTION_DUPLICATES d
            WHERE d.BATCH_ID = P_BATCH_ID
              AND d.SYSTEM_SIDE = 'TARGET'
              AND d.TRANSACTION_REF = TARGET_TRANSACTIONS.TRANSACTION_REF
       );

    -- Data-quality findings (idempotent by issue signature).
    INSERT INTO DATA_QUALITY_ISSUES(BATCH_ID, SYSTEM_SIDE, TRANSACTION_REF, ISSUE_TYPE, ISSUE_DETAILS)
    SELECT P_BATCH_ID, 'SOURCE', s.TRANSACTION_REF,
           CASE WHEN s.TRANSACTION_REF IS NULL THEN 'NULL_REFERENCE' ELSE 'NULL_AMOUNT' END,
           CASE WHEN s.TRANSACTION_REF IS NULL THEN 'Source transaction reference is null.'
                ELSE 'Source transaction amount is null.' END
      FROM SOURCE_TRANSACTIONS s
     WHERE s.BATCH_ID = P_BATCH_ID
       AND (s.TRANSACTION_REF IS NULL OR s.AMOUNT IS NULL)
       AND NOT EXISTS (
           SELECT 1 FROM DATA_QUALITY_ISSUES q
            WHERE q.BATCH_ID = P_BATCH_ID AND q.SYSTEM_SIDE = 'SOURCE'
              AND q.TRANSACTION_REF = s.TRANSACTION_REF
              AND q.ISSUE_TYPE = CASE WHEN s.TRANSACTION_REF IS NULL THEN 'NULL_REFERENCE' ELSE 'NULL_AMOUNT' END
       );

    INSERT INTO DATA_QUALITY_ISSUES(BATCH_ID, SYSTEM_SIDE, TRANSACTION_REF, ISSUE_TYPE, ISSUE_DETAILS)
    SELECT P_BATCH_ID, 'TARGET', t.TRANSACTION_REF,
           CASE WHEN t.TRANSACTION_REF IS NULL THEN 'NULL_REFERENCE' ELSE 'NULL_AMOUNT' END,
           CASE WHEN t.TRANSACTION_REF IS NULL THEN 'Target transaction reference is null.'
                ELSE 'Target transaction amount is null.' END
      FROM TARGET_TRANSACTIONS t
     WHERE t.BATCH_ID = P_BATCH_ID
       AND (t.TRANSACTION_REF IS NULL OR t.AMOUNT IS NULL)
       AND NOT EXISTS (
           SELECT 1 FROM DATA_QUALITY_ISSUES q
            WHERE q.BATCH_ID = P_BATCH_ID AND q.SYSTEM_SIDE = 'TARGET'
              AND q.TRANSACTION_REF = t.TRANSACTION_REF
              AND q.ISSUE_TYPE = CASE WHEN t.TRANSACTION_REF IS NULL THEN 'NULL_REFERENCE' ELSE 'NULL_AMOUNT' END
       );

    -- Only pair references unique on both sides. Duplicate groups are excluded
    -- from the join so duplicate rows cannot multiply reconciliation results.
    INSERT INTO RECON_RECORDS (
        BATCH_ID, TRANSACTION_REF, SOURCE_AMOUNT, TARGET_AMOUNT, RECON_STATUS
    )
    WITH
    S AS (
        SELECT s.*
          FROM SOURCE_TRANSACTIONS s
         WHERE s.BATCH_ID = P_BATCH_ID
           AND s.TRANSACTION_REF IS NOT NULL
           AND NOT EXISTS (
               SELECT 1 FROM SOURCE_TRANSACTIONS sx
                WHERE sx.BATCH_ID = s.BATCH_ID
                  AND sx.TRANSACTION_REF = s.TRANSACTION_REF
                GROUP BY sx.BATCH_ID, sx.TRANSACTION_REF
               HAVING COUNT(*) > 1
           )
    ),
    T AS (
        SELECT t.*
          FROM TARGET_TRANSACTIONS t
         WHERE t.BATCH_ID = P_BATCH_ID
           AND t.TRANSACTION_REF IS NOT NULL
           AND NOT EXISTS (
               SELECT 1 FROM TARGET_TRANSACTIONS tx
                WHERE tx.BATCH_ID = t.BATCH_ID
                  AND tx.TRANSACTION_REF = t.TRANSACTION_REF
                GROUP BY tx.BATCH_ID, tx.TRANSACTION_REF
               HAVING COUNT(*) > 1
           )
    )
    SELECT P_BATCH_ID,
           COALESCE(s.TRANSACTION_REF, t.TRANSACTION_REF),
           s.AMOUNT, t.AMOUNT,
           CASE
             WHEN s.TRANSACTION_REF IS NULL THEN 'MISSING_IN_SOURCE'
             WHEN t.TRANSACTION_REF IS NULL THEN 'MISSING_IN_TARGET'
             WHEN s.AMOUNT IS NULL OR t.AMOUNT IS NULL THEN 'MISSING_DATA'
             WHEN NVL(s.CURRENCY_CODE,'?') <> NVL(t.CURRENCY_CODE,'?') THEN 'CURRENCY_MISMATCH'
             WHEN s.AMOUNT = t.AMOUNT THEN 'MATCHED'
             ELSE 'MISMATCH'
           END
      FROM S s
      FULL OUTER JOIN T t
        ON s.BATCH_ID = t.BATCH_ID
       AND s.TRANSACTION_REF = t.TRANSACTION_REF
     WHERE COALESCE(s.BATCH_ID,t.BATCH_ID) = P_BATCH_ID
       AND NOT EXISTS (
           SELECT 1 FROM RECON_RECORDS r
            WHERE r.BATCH_ID = P_BATCH_ID
              AND r.TRANSACTION_REF = COALESCE(s.TRANSACTION_REF,t.TRANSACTION_REF)
       );

    -- Create exception rows for discrepancy outcomes.
    PKG_RECON_SUPPORT.PRC_LOAD_EXCEPTIONS(P_BATCH_ID);

    -- Capture control totals for both sides.
    MERGE INTO BATCH_CONTROL_TOTALS d
    USING (
        SELECT P_BATCH_ID BATCH_ID, 'SOURCE' SYSTEM_SIDE,
               COUNT(*) TRANSACTION_COUNT, SUM(AMOUNT) TOTAL_AMOUNT,
               MIN(CURRENCY_CODE) CURRENCY_CODE
          FROM SOURCE_TRANSACTIONS WHERE BATCH_ID = P_BATCH_ID
        UNION ALL
        SELECT P_BATCH_ID, 'TARGET', COUNT(*), SUM(AMOUNT), MIN(CURRENCY_CODE)
          FROM TARGET_TRANSACTIONS WHERE BATCH_ID = P_BATCH_ID
    ) s
       ON (d.BATCH_ID = s.BATCH_ID AND d.SYSTEM_SIDE = s.SYSTEM_SIDE)
    WHEN MATCHED THEN UPDATE SET
        d.TRANSACTION_COUNT = s.TRANSACTION_COUNT,
        d.TOTAL_AMOUNT = s.TOTAL_AMOUNT,
        d.CURRENCY_CODE = s.CURRENCY_CODE,
        d.CAPTURED_AT = SYSTIMESTAMP
    WHEN NOT MATCHED THEN INSERT
        (BATCH_ID, SYSTEM_SIDE, TRANSACTION_COUNT, TOTAL_AMOUNT, CURRENCY_CODE, CAPTURED_AT)
        VALUES (s.BATCH_ID, s.SYSTEM_SIDE, s.TRANSACTION_COUNT, s.TOTAL_AMOUNT, s.CURRENCY_CODE, SYSTIMESTAMP);

    SELECT COUNT(*) INTO V_SOURCE_COUNT FROM SOURCE_TRANSACTIONS WHERE BATCH_ID=P_BATCH_ID;
    SELECT COUNT(*) INTO V_TARGET_COUNT FROM TARGET_TRANSACTIONS WHERE BATCH_ID=P_BATCH_ID;
    SELECT COUNT(*) INTO V_RECON_COUNT FROM RECON_RECORDS WHERE BATCH_ID=P_BATCH_ID;

    UPDATE RECON_RUN_HISTORY
       SET RUN_STATUS='COMPLETED', ENDED_AT=SYSTIMESTAMP,
           SOURCE_ROW_COUNT=V_SOURCE_COUNT, TARGET_ROW_COUNT=V_TARGET_COUNT,
           RECON_ROW_COUNT=V_RECON_COUNT
     WHERE RUN_ID=V_RUN_ID;

    UPDATE RECON_BATCHES SET BATCH_STATUS='COMPLETED' WHERE BATCH_ID=P_BATCH_ID;

    PKG_RECON_SUPPORT.PRC_LOG_EVENT(
        P_BATCH_ID, V_RUN_ID, 'RECON_COMPLETE', 'SUCCESS',
        'Reconciliation completed. Source rows='||V_SOURCE_COUNT||
        ', target rows='||V_TARGET_COUNT||', reconciliation rows='||V_RECON_COUNT
    );
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20100, 'Batch ID does not exist.');
    WHEN OTHERS THEN
        IF V_RUN_ID IS NOT NULL THEN
            UPDATE RECON_RUN_HISTORY
               SET RUN_STATUS='FAILED', ENDED_AT=SYSTIMESTAMP,
                   ERROR_CODE=SQLCODE, ERROR_MESSAGE=SUBSTR(SQLERRM,1,2000)
             WHERE RUN_ID=V_RUN_ID;
            PKG_RECON_SUPPORT.PRC_LOG_EVENT(
                P_BATCH_ID, V_RUN_ID, 'RECON_FAILURE', 'ERROR', SQLERRM
            );
        END IF;
        UPDATE RECON_BATCHES SET BATCH_STATUS='FAILED' WHERE BATCH_ID=P_BATCH_ID;
        RAISE;
END PRC_RECONCILE_BATCH_V2;
