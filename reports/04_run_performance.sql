SELECT
    RUN_ID,
    BATCH_ID,
    RUN_NUMBER,
    RUN_STATUS,
    STARTED_AT,
    ENDED_AT,
    ROUND((CAST(ENDED_AT AS DATE)-CAST(STARTED_AT AS DATE))*86400,2) AS ELAPSED_SECONDS,
    SOURCE_ROW_COUNT,
    TARGET_ROW_COUNT,
    RECON_ROW_COUNT,
    ERROR_CODE,
    ERROR_MESSAGE
FROM RECON_RUN_HISTORY
ORDER BY RUN_ID DESC;

SELECT EVENT_AT, EVENT_TYPE, EVENT_STATUS, EVENT_MESSAGE, DB_USER_NAME
FROM RECON_AUDIT_LOG
ORDER BY AUDIT_ID DESC;
