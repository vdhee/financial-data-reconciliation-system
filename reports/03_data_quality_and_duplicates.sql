SELECT SYSTEM_SIDE, ISSUE_TYPE, ISSUE_STATUS, COUNT(*) AS ISSUE_COUNT
FROM DATA_QUALITY_ISSUES
GROUP BY SYSTEM_SIDE, ISSUE_TYPE, ISSUE_STATUS
ORDER BY SYSTEM_SIDE, ISSUE_TYPE, ISSUE_STATUS;

SELECT SYSTEM_SIDE, TRANSACTION_REF, DUPLICATE_COUNT, DETECTED_AT
FROM TRANSACTION_DUPLICATES
ORDER BY BATCH_ID, SYSTEM_SIDE, TRANSACTION_REF;

SELECT
    BATCH_ID,
    SYSTEM_SIDE,
    SUM(TRANSACTION_COUNT) AS ROWS_CAPTURED,
    SUM(TOTAL_AMOUNT) AS TOTAL_AMOUNT,
    COUNT(DISTINCT CURRENCY_CODE) AS CURRENCY_COUNT
FROM BATCH_CONTROL_TOTALS
GROUP BY BATCH_ID, SYSTEM_SIDE
ORDER BY BATCH_ID, SYSTEM_SIDE;
