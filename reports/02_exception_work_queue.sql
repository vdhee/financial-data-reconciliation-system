SELECT
    e.EXCEPTION_ID,
    r.BATCH_ID,
    r.TRANSACTION_REF,
    e.EXCEPTION_TYPE,
    e.EXCEPTION_AMOUNT,
    e.EXCEPTION_STATUS,
    e.CREATED_AT,
    TRUNC(SYSDATE) - TRUNC(CAST(e.CREATED_AT AS DATE)) AS AGE_DAYS
FROM RECON_EXCEPTIONS e
JOIN RECON_RECORDS r ON r.RECORD_ID=e.RECORD_ID
WHERE e.EXCEPTION_STATUS <> 'RESOLVED'
ORDER BY
    CASE e.EXCEPTION_TYPE
      WHEN 'CURRENCY_MISMATCH' THEN 1
      WHEN 'MISMATCH' THEN 2
      WHEN 'MISSING_IN_SOURCE' THEN 3
      WHEN 'MISSING_IN_TARGET' THEN 4
      ELSE 5
    END,
    e.CREATED_AT;

-- Work queue totals by status and type.
SELECT
    e.EXCEPTION_TYPE,
    e.EXCEPTION_STATUS,
    COUNT(*) AS EXCEPTION_COUNT,
    SUM(NVL(e.EXCEPTION_AMOUNT,0)) AS TOTAL_EXCEPTION_AMOUNT
FROM RECON_EXCEPTIONS e
WHERE e.EXCEPTION_STATUS <> 'RESOLVED'
GROUP BY e.EXCEPTION_TYPE,e.EXCEPTION_STATUS
ORDER BY e.EXCEPTION_TYPE,e.EXCEPTION_STATUS;
