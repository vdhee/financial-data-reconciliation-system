-- All queries are read-only. Empty results from the final two checks are expected.
SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
 'SOURCE_SYSTEMS','CURRENCY_REFERENCE','RECON_RULES','RECON_RUN_HISTORY',
 'BATCH_CONTROL_TOTALS','DATA_QUALITY_ISSUES','TRANSACTION_DUPLICATES',
 'EXCEPTION_ASSIGNMENTS','EXCEPTION_HISTORY','RECON_AUDIT_LOG'
)
ORDER BY TABLE_NAME;

SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM USER_OBJECTS
WHERE OBJECT_NAME IN ('PKG_RECON_SUPPORT','PRC_RECONCILE_BATCH_V2')
ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT NAME, TYPE, LINE, POSITION, TEXT
FROM USER_ERRORS
WHERE NAME IN ('PKG_RECON_SUPPORT','PRC_RECONCILE_BATCH_V2')
ORDER BY NAME, SEQUENCE;

SELECT BATCH_ID, TRANSACTION_REF, COUNT(*) AS CNT
FROM RECON_RECORDS
GROUP BY BATCH_ID, TRANSACTION_REF
HAVING COUNT(*) > 1;
