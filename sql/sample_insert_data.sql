INSERT INTO RECON_EXCEPTIONS (
    RECORD_ID,
    EXCEPTION_TYPE,
    EXCEPTION_AMOUNT
)
SELECT
    RECORD_ID,
    RECON_STATUS,
    CASE
        WHEN RECON_STATUS = 'MISMATCH'
            THEN ABS(SOURCE_AMOUNT - TARGET_AMOUNT)
        ELSE NULL
    END
FROM RECON_RECORDS
WHERE BATCH_ID = 1
  AND RECON_STATUS IN (
      'MISMATCH',
      'MISSING_IN_SOURCE',
      'MISSING_IN_TARGET',
      'MISSING_DATA'
  )
  AND TRANSACTION_REF LIKE 'TXN200%'
  AND NOT EXISTS (
      SELECT 1
      FROM RECON_EXCEPTIONS e
      WHERE e.RECORD_ID = RECON_RECORDS.RECORD_ID
  );

COMMIT;


select * from RECON_EXCEPTIONS;