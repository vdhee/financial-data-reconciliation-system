CREATE TABLE RECON_RECORDS (
    RECORD_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BATCH_ID NUMBER NOT NULL,
    TRANSACTION_REF VARCHAR2(100) NOT NULL,
    SOURCE_AMOUNT NUMBER(15,2),
    TARGET_AMOUNT NUMBER(15,2),
    RECON_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,

    CONSTRAINT FK_RECORD_BATCH
        FOREIGN KEY (BATCH_ID)
        REFERENCES RECON_BATCHES(BATCH_ID),

    CONSTRAINT CHK_RECON_STATUS
        CHECK (RECON_STATUS IN (
            'PENDING', 'MATCHED', 'MISMATCH'
        ))
);

CREATE INDEX IDX_RECON_RECORDS_BATCH
ON RECON_RECORDS (BATCH_ID);