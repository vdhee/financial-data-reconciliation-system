
INSERT INTO RECON_EXCEPTIONS (
    RECORD_ID,
    EXCEPTION_TYPE,
    EXCEPTION_AMOUNT
)
SELECT
    r.RECORD_ID,
    r.RECON_STATUS,
    CASE
        WHEN r.RECON_STATUS = 'MISMATCH'
            THEN ABS(r.SOURCE_AMOUNT - r.TARGET_AMOUNT)
        ELSE NULL
    END
FROM RECON_RECORDS r
WHERE r.BATCH_ID = 1
  AND r.RECON_STATUS IN (
      'MISMATCH',
      'MISSING_IN_SOURCE',
      'MISSING_IN_TARGET',
      'MISSING_DATA'
  )
  AND r.TRANSACTION_REF LIKE 'TXN200%'
  AND NOT EXISTS (
      SELECT 1
      FROM RECON_EXCEPTIONS e
      WHERE e.RECORD_ID = r.RECORD_ID
  );

COMMIT;
