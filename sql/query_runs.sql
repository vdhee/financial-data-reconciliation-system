--calculate reconciliation rate for batch 1
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    SUM(CASE
        WHEN RECON_STATUS = 'MATCHED' THEN 1
        ELSE 0
    END) AS MATCHED_RECORDS,
    SUM(CASE
        WHEN RECON_STATUS = 'MISSING_DATA' THEN 1
        ELSE 0
    END) AS MISSING_DATA_RECORDS,
    ROUND(
        100 * SUM(CASE
            WHEN RECON_STATUS = 'MATCHED' THEN 1
            ELSE 0
        END)
        / NULLIF(
            SUM(CASE
                WHEN RECON_STATUS IN ('MATCHED', 'MISMATCH')
                THEN 1
                ELSE 0
            END),
            0
        ),
        2
    ) AS MATCH_RATE_PCT
FROM RECON_RECORDS
WHERE BATCH_ID = 1;


