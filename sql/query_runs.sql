---transaction difference for batch 1
SELECT
    TRANSACTION_REF,
    SOURCE_AMOUNT,
    TARGET_AMOUNT,
    CASE
        WHEN SOURCE_AMOUNT IS NULL
          OR TARGET_AMOUNT IS NULL
            THEN NULL
        ELSE ABS(SOURCE_AMOUNT - TARGET_AMOUNT)
    END AS DIFFERENCE_AMOUNT,
    RECON_STATUS
FROM RECON_RECORDS
WHERE BATCH_ID = 1
ORDER BY RECORD_ID;


---summary of recon status for batch 1
SELECT
    RECON_STATUS,
    COUNT(*) AS TOTAL_RECORDS
FROM RECON_RECORDS
WHERE BATCH_ID = 1
GROUP BY RECON_STATUS
ORDER BY RECON_STATUS;


--calculate reconciliation rate for batch 1
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    SUM(CASE
        WHEN RECON_STATUS = 'MATCHED' THEN 1
        ELSE 0
    END) AS MATCHED_RECORDS,
    ROUND(
        100.0 * SUM(CASE
            WHEN RECON_STATUS = 'MATCHED' THEN 1
            ELSE 0
        END) / NULLIF(COUNT(*), 0),
        2
    ) AS RECONCILIATION_RATE
FROM RECON_RECORDS
WHERE BATCH_ID = 1;


--returns only mismatched transactions
SELECT
    TRANSACTION_REF,
    SOURCE_AMOUNT,
    TARGET_AMOUNT,
    ABS(SOURCE_AMOUNT - TARGET_AMOUNT) AS DIFFERENCE_AMOUNT
FROM RECON_RECORDS
WHERE BATCH_ID = 1
  AND RECON_STATUS = 'MISMATCH'
ORDER BY DIFFERENCE_AMOUNT DESC;


--find missing amount
SELECT
    TRANSACTION_REF,
    SOURCE_AMOUNT,
    TARGET_AMOUNT,
    RECON_STATUS
FROM RECON_RECORDS
WHERE BATCH_ID = 1
  AND (
      SOURCE_AMOUNT IS NULL
      OR TARGET_AMOUNT IS NULL
  );

