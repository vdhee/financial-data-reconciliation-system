CREATE TABLE SOURCE_TRANSACTIONS (
    SOURCE_TXN_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BATCH_ID NUMBER NOT NULL,
    TRANSACTION_REF VARCHAR2(100) NOT NULL,
    TRANSACTION_DATE DATE,
    AMOUNT NUMBER(15,2),
    CURRENCY_CODE VARCHAR2(3),
    LOAD_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_SOURCE_BATCH
        FOREIGN KEY (BATCH_ID)
        REFERENCES RECON_BATCHES(BATCH_ID)
);