CREATE TABLE RECON_EXCEPTIONS (
    EXCEPTION_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RECORD_ID NUMBER NOT NULL,
    EXCEPTION_TYPE VARCHAR2(30) NOT NULL,
    EXCEPTION_AMOUNT NUMBER(15,2),
    EXCEPTION_STATUS VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    RESOLVED_AT TIMESTAMP,

    CONSTRAINT FK_EXCEPTION_RECORD
        FOREIGN KEY (RECORD_ID)
        REFERENCES RECON_RECORDS(RECORD_ID),

    CONSTRAINT CHK_EXCEPTION_TYPE
        CHECK (
            EXCEPTION_TYPE IN (
                'MISMATCH',
                'MISSING_IN_SOURCE',
                'MISSING_IN_TARGET',
                'MISSING_DATA'
            )
        ),

    CONSTRAINT CHK_EXCEPTION_STATUS
        CHECK (
            EXCEPTION_STATUS IN (
                'OPEN',
                'INVESTIGATING',
                'RESOLVED'
            )
        )
);