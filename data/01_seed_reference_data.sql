MERGE INTO SOURCE_SYSTEMS d USING (
    SELECT 'BANK_SYSTEM' SYSTEM_CODE, 'Bank Payment Platform' SYSTEM_NAME, 'SOURCE' SYSTEM_ROLE FROM DUAL
    UNION ALL SELECT 'ACCOUNTING_SYSTEM', 'General Ledger Platform', 'TARGET' FROM DUAL
    UNION ALL SELECT 'CARD_PROCESSOR', 'Card Processing Platform', 'BOTH' FROM DUAL
) s ON (d.SYSTEM_CODE=s.SYSTEM_CODE)
WHEN MATCHED THEN UPDATE SET d.SYSTEM_NAME=s.SYSTEM_NAME, d.SYSTEM_ROLE=s.SYSTEM_ROLE
WHEN NOT MATCHED THEN INSERT (SYSTEM_CODE,SYSTEM_NAME,SYSTEM_ROLE)
VALUES (s.SYSTEM_CODE,s.SYSTEM_NAME,s.SYSTEM_ROLE);

MERGE INTO CURRENCY_REFERENCE d USING (
    SELECT 'INR' CURRENCY_CODE, 'Indian Rupee' CURRENCY_NAME, 2 DECIMAL_PLACES FROM DUAL
    UNION ALL SELECT 'USD','United States Dollar',2 FROM DUAL
    UNION ALL SELECT 'EUR','Euro',2 FROM DUAL
    UNION ALL SELECT 'JPY','Japanese Yen',0 FROM DUAL
) s ON (d.CURRENCY_CODE=s.CURRENCY_CODE)
WHEN MATCHED THEN UPDATE SET d.CURRENCY_NAME=s.CURRENCY_NAME, d.DECIMAL_PLACES=s.DECIMAL_PLACES
WHEN NOT MATCHED THEN INSERT (CURRENCY_CODE,CURRENCY_NAME,DECIMAL_PLACES)
VALUES (s.CURRENCY_CODE,s.CURRENCY_NAME,s.DECIMAL_PLACES);

MERGE INTO RECON_RULES d USING (
    SELECT 'AMOUNT_EXACT' RULE_CODE, 'Exact amount comparison' RULE_NAME, 'AMOUNT' RULE_TYPE, 0 AMOUNT_TOLERANCE, 'HIGH' SEVERITY FROM DUAL
    UNION ALL SELECT 'CURRENCY_EQUAL','Currency must match','CURRENCY',0,'HIGH' FROM DUAL
    UNION ALL SELECT 'MISSING_SIDE','Transaction must exist on both sides','MISSING',0,'CRITICAL' FROM DUAL
    UNION ALL SELECT 'DUPLICATE_REF','Transaction reference must be unique per side','DUPLICATE',0,'HIGH' FROM DUAL
    UNION ALL SELECT 'REQUIRED_FIELDS','Required transaction fields must be populated','DATA_QUALITY',0,'HIGH' FROM DUAL
) s ON (d.RULE_CODE=s.RULE_CODE)
WHEN MATCHED THEN UPDATE SET d.RULE_NAME=s.RULE_NAME, d.RULE_TYPE=s.RULE_TYPE,
    d.AMOUNT_TOLERANCE=s.AMOUNT_TOLERANCE, d.SEVERITY=s.SEVERITY
WHEN NOT MATCHED THEN INSERT
    (RULE_CODE,RULE_NAME,RULE_TYPE,AMOUNT_TOLERANCE,SEVERITY)
VALUES (s.RULE_CODE,s.RULE_NAME,s.RULE_TYPE,s.AMOUNT_TOLERANCE,s.SEVERITY);

